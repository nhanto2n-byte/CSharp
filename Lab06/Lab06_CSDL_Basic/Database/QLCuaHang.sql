IF DB_ID(N'QLCuaHang') IS NULL CREATE DATABASE QLCuaHang;
GO
USE QLCuaHang;
GO
IF OBJECT_ID('dbo.CHITIET_HOADON','U') IS NOT NULL DROP TABLE dbo.CHITIET_HOADON;
IF OBJECT_ID('dbo.TONKHO','U') IS NOT NULL DROP TABLE dbo.TONKHO;
IF OBJECT_ID('dbo.HOADON','U') IS NOT NULL DROP TABLE dbo.HOADON;
IF OBJECT_ID('dbo.SANPHAM','U') IS NOT NULL DROP TABLE dbo.SANPHAM;
GO
CREATE TABLE dbo.SANPHAM(MaSP INT IDENTITY(1,1) PRIMARY KEY,TenSP NVARCHAR(120) NOT NULL);
CREATE TABLE dbo.HOADON(MaHD INT IDENTITY(1,1) PRIMARY KEY,NgayTao DATE NOT NULL,TinhTrangThanhToan BIT NOT NULL DEFAULT(0));
CREATE TABLE dbo.TONKHO(MaSP INT NOT NULL,NgayTon DATE NOT NULL,SLDau INT NOT NULL DEFAULT(0),SLNhap INT NOT NULL DEFAULT(0),SLBan INT NOT NULL DEFAULT(0),
CONSTRAINT PK_TONKHO PRIMARY KEY(MaSP,NgayTon),CONSTRAINT FK_TONKHO_SP FOREIGN KEY(MaSP) REFERENCES dbo.SANPHAM(MaSP),CONSTRAINT CK_TONKHO CHECK(SLDau>=0 AND SLNhap>=0 AND SLBan>=0));
CREATE TABLE dbo.CHITIET_HOADON(MaHD INT NOT NULL,MaSP INT NOT NULL,SoLuong INT NOT NULL CHECK(SoLuong>0),
CONSTRAINT PK_CTHD PRIMARY KEY(MaHD,MaSP),CONSTRAINT FK_CTHD_HD FOREIGN KEY(MaHD) REFERENCES dbo.HOADON(MaHD),CONSTRAINT FK_CTHD_SP FOREIGN KEY(MaSP) REFERENCES dbo.SANPHAM(MaSP));
